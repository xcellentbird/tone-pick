/**
 * 일련번호를 한글로 읽는다 — 닉네임에 숫자를 쓸 수 없어서 `손님3` 대신 `손님삼`.
 * 가짜 사람을 만드는 곳(테스트 픽스처·부하 리허설)이 쓴다.
 * scripts/rehearsal.mjs 만 예외다 — 노드 스크립트라 TS 를 못 불러와 같은 표를 복제해 둔다.
 */
export function hangulSeq(n: number): string {
  // copy-ok
  const DIGITS = "영일이삼사오육칠팔구";
  return String(n).replace(/[0-9]/g, (d) => DIGITS[Number(d)]);
}

